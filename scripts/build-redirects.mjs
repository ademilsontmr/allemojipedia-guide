// Runs after `astro build`. Writes dist/_redirects (Cloudflare Pages) mapping the pre-2026-11
// URL structure onto the rebuilt site. Limits: 2,000 static + 100 dynamic rules.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
const emojis = JSON.parse(readFileSync("src/data/emojis.json", "utf8"));
const legacy = JSON.parse(readFileSync("src/data/legacy-emoji-slugs.json", "utf8"));
const strip = (s) => s.replace(/️/g, "");
const byChar = new Map(emojis.map((e) => [strip(e.emoji), e]));
const hasPage = (slug) => existsSync(`dist/emojis/${slug}/index.html`);
const hasGuide = (slug) => existsSync(`dist/guides/${slug}/index.html`);
const lines = [
  "# Generated by scripts/build-redirects.mjs. Do not edit dist/_redirects by hand.",
  "http://allemojipedia.com/* https://allemojipedia.com/:splat 301!",
  "http://www.allemojipedia.com/* https://allemojipedia.com/:splat 301!",
  "https://www.allemojipedia.com/* https://allemojipedia.com/:splat 301!",
  "/favicon.ico /favicon-48x48.png 200",
  "",
  "# Old emoji pages (/emoji/<slug>/) that have a new in-depth page",
];
let n = 0;
for (const [oldSlug, char] of Object.entries(legacy)) {
  const e = byChar.get(strip(char));
  if (e && hasPage(e.slug)) { lines.push(`/emoji/${oldSlug} /emojis/${e.slug}/ 301`, `/emoji/${oldSlug}/ /emojis/${e.slug}/ 301`); n += 2; }
}
const guide = (from, slug, fallback = "/guides/") => { const to = hasGuide(slug) ? `/guides/${slug}/` : fallback; lines.push(`${from} ${to} 301`, `${from}/ ${to} 301`); n += 2; };
lines.push("", "# Old blog posts and hubs with a direct successor");
for (const [from, slug] of [
  ["/blog/heart-emoji-meanings-guide", "heart-emoji-colors-meaning"], ["/blog/gen-z-emoji-meanings-decoded", "gen-z-emoji-slang"],
  ["/blog/emoji-meaning-texting-guide", "emoji-meanings-in-texting"], ["/blog/flirty-emoji-meanings-romantic-or-friendly", "flirty-emojis-guide"],
  ["/blog/emoji-meanings-from-a-girl-or-guy", "emojis-from-a-guy-vs-a-girl"], ["/blog/whatsapp-emoji-meanings-tone-guide", "whatsapp-emoji-meanings"],
  ["/blog/instagram-emoji-meanings-comments-dms", "instagram-emoji-meanings"], ["/blog/tiktok-emoji-meanings-gen-z-slang", "tiktok-emoji-meanings"],
  ["/blog/how-to-use-emojis-at-work", "emojis-at-work-etiquette"], ["/blog/emoji-etiquette-professional", "emojis-at-work-etiquette"],
  ["/blog/evolution-of-emojis", "history-of-emoji"], ["/blog/complete-history-emoticons-emojis", "history-of-emoji"],
  ["/blog/emoji-kitchen-guide", "emoji-kitchen-guide"], ["/blog/emoji-accessibility", "emoji-accessibility-screen-readers"],
  ["/blog/cultural-differences-emojis", "emojis-across-cultures"], ["/blog/emojis-in-marketing", "emojis-in-marketing"],
  ["/blog/flag-emojis-complete-guide", "flag-emojis-explained"], ["/blog/european-flags-that-look-similar", "flags-that-look-alike"],
  ["/blog/complete-guide-emoji-keyboards", "how-to-type-emojis-on-any-device"], ["/blog/iphone-emojis-on-android", "iphone-vs-android-emojis"],
  ["/blog/emoji-combinations", "emoji-combos-ideas"], ["/emoji-meanings-in-texting", "emoji-meanings-in-texting"],
  ["/emoji-kitchen", "emoji-kitchen-guide"], ["/tiktok-emojis", "tiktok-emoji-meanings"], ["/emoji-combos", "emoji-combos-ideas"],
  ["/platforms", "iphone-vs-android-emojis"], ["/apple", "iphone-vs-android-emojis"], ["/iphone-emojis", "iphone-vs-android-emojis"],
  ["/android-emojis", "iphone-vs-android-emojis"], ["/google-emojis", "iphone-vs-android-emojis"], ["/samsung-emojis", "iphone-vs-android-emojis"],
]) guide(from, slug);
lines.push("", "# Other old sections");
for (const [from, to] of [
  ["/flag-quiz", "/flag-emoji-quiz/"], ["/blog", "/guides/"], ["/emoji-meanings", "/emojis/"], ["/emoji-comparisons", "/emojis/"],
  ["/emoji-copy-and-paste", "/categories/"], ["/copy-iphone-emojis", "/categories/"], ["/copy-android-emojis", "/categories/"],
  ["/copy-samsung-emojis", "/categories/"], ["/people", "/categories/people-and-body/"], ["/sitemap", "/categories/"],
]) { lines.push(`${from} ${to} 301`, `${from}/ ${to} 301`); n += 2; }
lines.push(
  "", "# Catch-alls (dynamic rules; evaluated after the static ones above)",
  "/category/:slug /categories/:slug/ 301", "/category/:slug/ /categories/:slug/ 301",
  "/emoji/* /emojis/ 301", "/blog/* /guides/ 301", "/emoji-meanings/* /emojis/ 301", "/emoji-combos/* /guides/ 301",
  "/people/* /categories/people-and-body/ 301", "/platforms/* /guides/ 301", "/emoji-meanings-in-texting/* /emojis/ 301", "",
);
if (n > 2000) throw new Error(`Too many static redirects for Cloudflare Pages: ${n}`);
writeFileSync("dist/_redirects", lines.join("\n"));
console.log(`_redirects: ${n} static rules`);
